    def test_wrong_linked_or_unowned_copied_controller_refuses(self):
        child = self.runtime / '.runs/qualify-current-method-001.py'
        outside = self.base / 'retained child'
        outside.write_bytes((self.admin / 'scripts/qualify_current_method.py').read_bytes())
        for kind in ('wrong', 'symlink', 'hardlink', 'unowned'):
            with self.subTest(kind=kind):
                if kind == 'wrong': child.write_bytes(b'not the public controller')
                elif kind == 'symlink': child.symlink_to(outside)
                elif kind == 'hardlink': os.link(outside, child)
                else: child.write_bytes(outside.read_bytes())
                original_stat = Path.stat
                def stat(path, *, follow_symlinks=True):
                    value = original_stat(path, follow_symlinks=follow_symlinks)
                    if kind == 'unowned' and path == child and follow_symlinks:
                        fields = list(value); fields[4] += 1
                        return os.stat_result(fields)
                    return value
                with mock.patch.object(Path, 'stat', stat): self.refused()
                self.assertFalse(self.calls)
                self.assertFalse(self.output.exists())
                child.unlink()

