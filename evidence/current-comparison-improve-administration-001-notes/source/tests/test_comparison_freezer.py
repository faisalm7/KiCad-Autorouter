        self.assertEqual(population['families']['owned']['publication'], 'hashes_only')
        self.assertIn('not legal clearance', population['caveats'])
        self.assertEqual(q.io.inventory(self.project), original)
        for arm, item in result['protocols']['owned'].items():
            path = Path(item['path'])
            self.assertEqual(sha(path.read_bytes()), item['sha256'])
            plan = json.loads(path.read_text())
            self.assertEqual(plan['whole_wall_full_cpu_seconds'], 600)
            self.assertEqual(plan['source_hashes'], original)
            self.assertEqual(plan['tools'], self.query['tools'])
