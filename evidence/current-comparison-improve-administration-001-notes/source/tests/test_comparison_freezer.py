    def fake_query(self, argv, **kwargs):
        self.calls.append((argv, kwargs))
        raw = (json.dumps(self.query, sort_keys=True) + '\n').encode()
        kwargs['log'].write_bytes(raw)
        process = dict(status='success', exit_code=0, cleanup_complete=True, log_truncated=False,
            log=str(kwargs['log']), log_bytes=len(raw), argv=argv, cwd=str(kwargs['cwd']))
        process.update(self.process_changes)
        if self.query_callback:
            self.query_callback()
        return process

