import argparse
import copy
import json
from pathlib import Path
import uuid

from autorouter import sexpr as sx
from experiments.native_schematic_transport_v1 import fixture as base

STEM = 'owned_hierarchy_native'
CHILD = 'owned_channel.kicad_sch'
SOURCE_ID = 'owned-hierarchy-native-v1'
NS = uuid.UUID('9619c7e4-6e8b-4e4f-bac8-949f73c0917c')
FIELD = 'OwnedHierarchyIdentity'
DUAL = 'OwnedHierarchy:Dual'
TERMINAL = 'OwnedHierarchy:Terminal'
ALIAS_ID = 'OwnedHierarchy:AliasTerminal'
ALIAS_KEY = 'AliasTerminalLegacy'
FP_DUAL = 'owned_hierarchy_dual'
FP_TERMINAL = 'owned_hierarchy_terminal'
FP_ALIAS = 'owned_hierarchy_alias'


def uid(label):
    return str(uuid.uuid5(NS, label))


def quote(value):
    return json.dumps(value, ensure_ascii=True)


def encoded(tree):
    return (sx.dump(tree) + '\n').encode()


def effects(*, hidden=False):
    value = ['effects', ['font', ['size', '1.27', '1.27']]]
    if hidden:
        value.append(['hide', 'yes'])
    return value


def sch_property(name, value, x='0', y='0', *, hidden=True):
    return ['property', quote(name), quote(value), ['at', x, y, '0'], effects(hidden=hidden)]


def component_fields(kind, identity):
    footprint, value = {
        'terminal': (FP_TERMINAL, 'OWNED_TERMINAL'),
        'dual': (FP_DUAL, 'OWNED_DUAL'),
        'alias': (FP_ALIAS, 'OWNED_ALIAS')}[kind]
    # Empty Datasheet on both SCH/PCB avoids depending on the separate flat-only
    # '~'/empty field bridge. Custom identity is constant across repeated uses
    # of one source symbol; full instance paths distinguish the physical parts.
    return [('Value', value), ('Footprint', footprint), ('Datasheet', ''),
            ('Description', 'Project-owned hierarchy qualification ' + kind),
            (FIELD, SOURCE_ID + '/' + identity)]


def lib_pin(number, x, *, facing='0', kind='passive'):
    return ['pin', kind, 'line', ['at', x, '0', facing], ['length', '1.27'],
            ['name', quote(number), effects()], ['number', quote(number), effects()]]


def rectangle():
    return ['rectangle', ['start', '-1.27', '1.27'], ['end', '1.27', '-1.27'],
            ['stroke', ['width', '0.254'], ['type', 'default']], ['fill', ['type', 'background']]]


def definition(key, kind):
    prefix = key.rsplit(':', 1)[-1]
    result = ['symbol', quote(key), ['pin_names', ['offset', '0'], 'hide'],
              ['exclude_from_sim', 'no'], ['in_bom', 'yes'], ['on_board', 'yes'],
              sch_property('Reference', 'U' if kind == 'dual' else 'J'),
              *[sch_property(name, value) for name, value in component_fields(kind, 'definition')]]
    common = ['symbol', quote(prefix + '_0_1'), rectangle()]
    if kind == 'dual':
        common.append(lib_pin('3', '-2.54', kind='power_in'))
        result.extend([common,
            ['symbol', quote(prefix + '_1_1'), lib_pin('1', '2.54', facing='180')],
            ['symbol', quote(prefix + '_2_1'), lib_pin('2', '2.54', facing='180')]])
    elif kind == 'alias':
        result.extend([common, ['symbol', quote(prefix + '_1_1'),
                       lib_pin('R', '-2.54'), lib_pin('T', '2.54', facing='180')]])
    else:
        result.extend([common, ['symbol', quote(prefix + '_1_1'), lib_pin('1', '-2.54')]])
    return result


def placed_symbol(label, lib_id, kind, unit, x, y, references, *, alias=None):
    value = ['symbol', ['lib_id', quote(lib_id)]]
    if alias is not None:
        value.append(['lib_name', quote(alias)])
    value += [['at', x, y, '0'], ['unit', str(unit)], ['exclude_from_sim', 'no'],
              ['in_bom', 'yes'], ['on_board', 'yes'], ['dnp', 'no'], ['uuid', quote(uid(label))],
              sch_property('Reference', references[0][1], x, y, hidden=False),
              *[sch_property(name, text, x, y, hidden=name != 'Value')
                for name, text in component_fields(kind, 'root-X' if kind == 'terminal' else 'child-' + kind)]]
    numbers = {'terminal': ('1',), 'dual': ('1', '2', '3'), 'alias': ('R', 'T')}[kind]
    value.extend(['pin', quote(number), ['uuid', quote(uid(label + '/pin/' + number))]] for number in numbers)
    value.append(['instances', ['project', quote(STEM),
                  *[['path', quote(path), ['reference', quote(ref)], ['unit', str(unit)]]
                    for path, ref in references]]])
    return value


def label(name, x, y, identity, *, global_net=False):
    value = [('global_label' if global_net else 'label'), quote(name)]
    if global_net:
        value.append(['shape', 'input'])
    value += [['at', x, y, '0'], ['effects', ['font', ['size', '1.27', '1.27']], ['justify', 'left']],
              ['uuid', quote(uid('label/' + identity))]]
    return value


def root_schematic():
    root_path = '/' + uid('root')
    tree = ['kicad_sch', ['version', '20250114'], ['generator', '"eeschema"'],
            ['generator_version', '"10.0"'], ['uuid', quote(uid('root'))], ['paper', '"A4"'],
            ['lib_symbols', definition(TERMINAL, 'terminal')],
            label('GND', '38.1', '40.64', 'root-GND', global_net=True),
            placed_symbol('root/X', TERMINAL, 'terminal', 1, '40.64', '40.64', [(root_path, 'X1')])]
    for page, name, y in ((2, 'A', '71.12'), (3, 'B', '101.6')):
        tree.append(['sheet', ['at', '40.64', y], ['size', '30.48', '15.24'],
             ['exclude_from_sim', 'no'], ['in_bom', 'yes'], ['on_board', 'yes'], ['dnp', 'no'],
             ['fields_autoplaced', 'yes'], ['stroke', ['width', '0.1524'], ['type', 'solid']],
             ['fill', ['color', '0', '0', '0', '0.0000']], ['uuid', quote(uid('sheet/' + name))],
             sch_property('Sheetname', name, '40.64', y, hidden=False),
             sch_property('Sheetfile', CHILD, '40.64', y, hidden=False),
             ['instances', ['project', quote(STEM), ['path', quote(root_path), ['page', quote(str(page))]]]]])
    tree.append(['embedded_fonts', 'no'])
    return encoded(tree)


def child_schematic():
    paths = [('/' + uid('root') + '/' + uid('sheet/' + name), index)
             for index, name in enumerate(('A', 'B'), 1)]
    tree = ['kicad_sch', ['version', '20250114'], ['generator', '"eeschema"'],
            ['generator_version', '"10.0"'], ['uuid', quote(uid('child'))], ['paper', '"A4"'],
            ['lib_symbols', definition(DUAL, 'dual'), definition(ALIAS_KEY, 'alias')]]
    # Every label anchor is exactly a library pin endpoint. All pins have local
    # y=0, avoiding any guessed library/placed-coordinate Y transformation.
    for unit, y, signal in ((1, '40.64', 'SIG_A'), (2, '71.12', 'SIG_B')):
        tree.extend([placed_symbol('child/U/' + str(unit), DUAL, 'dual', unit, '40.64', y,
                                  [(path, 'U' + str(index)) for path, index in paths]),
                     label('GND', '38.1', y, 'U%s-GND' % unit, global_net=True),
                     label(signal, '43.18', y, 'U%s-signal' % unit)])
    tree.extend([placed_symbol('child/J', ALIAS_ID, 'alias', 1, '81.28', '40.64',
                              [(path, 'J' + str(index)) for path, index in paths], alias=ALIAS_KEY),
                 label('SIG_A', '78.74', '40.64', 'J-signal'),
                 label('GND', '83.82', '40.64', 'J-GND', global_net=True), ['embedded_fonts', 'no']])
    return encoded(tree)


def pcb_property(ref, name, text):
    return ['property', quote(name), quote(text), ['at', '0', '0', '0'], ['layer', '"F.Fab"'],
            ['hide', 'yes'], ['uuid', quote(uid('pcb/%s/property/%s' % (ref, name)))],
            ['effects', ['font', ['size', '1', '1'], ['thickness', '0.15']]]]


def footprint(ref, kind, x, y, symbol_path, terminals):
    fpname = dict(terminal=FP_TERMINAL, dual=FP_DUAL, alias=FP_ALIAS)[kind]
    identity = 'root-X' if kind == 'terminal' else 'child-' + kind
    tree = ['footprint', quote(fpname), ['layer', '"F.Cu"'], ['uuid', quote(uid('pcb/' + ref))],
            ['at', x, y], pcb_property(ref, 'Reference', ref),
            *[pcb_property(ref, name, text) for name, text in component_fields(kind, identity) if name != 'Footprint'],
            ['path', quote(symbol_path)], ['attr', 'through_hole']]
    extent = '1.5' if kind == 'terminal' else '4.5'
    tree.append(['fp_rect', ['start', '-' + extent, '-' + extent], ['end', extent, extent],
                 ['stroke', ['width', '0.05'], ['type', 'default']], ['fill', 'none'],
                 ['layer', '"F.CrtYd"'], ['uuid', quote(uid('courtyard/' + ref))]])
    for index, (number, px, py, net) in enumerate(terminals):
        pad = ['pad', quote(number), 'thru_hole', 'circle', ['at', px, py], ['size', '2', '2'],
               ['drill', '0.8'], ['layers', '"*.Cu"', '"*.Mask"']]
        if net is not None:
            pad.extend([['net', quote(net)], ['pinfunction', quote(number)],
                        ['pintype', 'power_in' if kind == 'dual' and number == '3' else 'passive']])
        pad.append(['uuid', quote(uid('pcb/%s/pad/%s' % (ref, index)))])
        tree.append(pad)
    tree.append(['embedded_fonts', 'no'])
    return tree


def board():
    # Retain the already owned actual-Native fixture's complete layer/setup
    # grammar; replace its design population rather than editing a real board.
    original = sx.parse(base.board().decode())
    tree = [copy.deepcopy(row) for row in original if not isinstance(row, list) or
            row[0] in {'version', 'generator', 'generator_version', 'general', 'paper', 'layers', 'setup'}]
    tree.append(footprint('X1', 'terminal', '12', '12', '/' + uid('root/X'), [('1', '0', '0', 'GND')]))
    for name, index, y in (('A', 1, '12'), ('B', 2, '30')):
        prefix = '/' + uid('sheet/' + name) + '/'
        tree.extend([footprint('U' + str(index), 'dual', '24', y, prefix + uid('child/U/1'),
                              [('1', '-3', '0', '/' + name + '/SIG_A'),
                               ('2', '0', '0', '/' + name + '/SIG_B'), ('3', '3', '0', 'GND')]),
                     footprint('J' + str(index), 'alias', '40', y, prefix + uid('child/J'),
                              [('R', '-3', '0', '/' + name + '/SIG_A'), ('T', '3', '0', 'GND'),
                               ('MP', '0', '-3', None), ('MP', '0', '3', None)])])
    tree.extend([['gr_rect', ['start', '5', '5'], ['end', '48', '40'],
                 ['stroke', ['width', '0.05'], ['type', 'default']], ['fill', 'none'],
                 ['layer', '"Edge.Cuts"'], ['uuid', quote(uid('outline'))]], ['embedded_fonts', 'no']])
    return encoded(tree)


def project():
    value = json.loads(base.project())
    value['meta']['filename'] = STEM + '.kicad_pro'
    value['net_settings']['meta'] = {'version': 5}
    value['net_settings']['classes'][0]['priority'] = 2147483647
    return (json.dumps(value, indent=2, sort_keys=True) + '\n').encode()


def files():
    """Five source files, no generated netlist/report/route or copied library."""
    prl = {'meta': {'filename': STEM + '.kicad_prl', 'version': 5},
           'board': {'active_layer': 0, 'hidden_nets': [], 'hidden_netclasses': []}}
    return {STEM + '.kicad_pcb': board(), STEM + '.kicad_sch': root_schematic(),
            CHILD: child_schematic(), STEM + '.kicad_pro': project(),
            STEM + '.kicad_prl': (json.dumps(prl, indent=2, sort_keys=True) + '\n').encode()}


def write_project(output):
    output = Path(output)
    if (not output.is_absolute() or output.exists() or output.is_symlink()
            or output.parent.resolve() != output.parent or not output.parent.is_dir()
            or '..' in output.parts):
        raise ValueError('fresh canonical absolute output with existing parent required')
    material = files()
    output.mkdir()
    for name, raw in material.items():
        with (output / name).open('xb') as stream:
            stream.write(raw)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    write_project(parser.parse_args().output)
